// Lo straniero (da W0.4; in Ultimo raccolto era il superstite).
//
// Tre direzioni per quattro fotogrammi. La destra non esiste come disegno: è
// LATO riflesso a runtime (vedi riflesso() in sprite.js). Disegnare a mano è la
// risorsa più scarsa del progetto, e specchiare dimezza il lavoro senza che
// nessuno se ne accorga.
//
// Composti da busti e gambe intercambiabili: il busto è identico in tutti i
// fotogrammi di una direzione, così un ritocco al viso non va ripetuto quattro
// volte. Da qui in poi si ritoccano come dati.
//
// Da Per un pugno di semi W0.4 il busto è quello di un forestiero arrivato da
// nessuna parte: il cappello a tesa larga, il poncho con la fascia a punto
// sull'orlo, la barba di qualche giorno e il sigaro, che si vede solo di
// profilo — di fronte due pixel arancioni in mezzo alla faccia si leggevano
// come una ferita. Le gambe sono quelle di prima, e i jeans sono i vestiti
// blu del superstite: sotto il poncho non è cambiato niente.
//
// Otto chiavi sono sue (vedi tavolozza.js): M e N il cappello e la fascia,
// O P Q il poncho, R la parte bassa del viso, S e T il sigaro. R, S e T sono
// chiavi a parte per una ragione sola: i banditi sono questo stesso disegno
// cotto con un'altra tavolozza, e lì R è il fazzoletto sulla faccia e il
// sigaro non c'è.

