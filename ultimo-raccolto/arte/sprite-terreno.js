// Tasselli del terreno di Ultimo raccolto.
//
// Ogni tassello è 16x16 e ogni carattere è una chiave della tavolozza. Sono
// nati da una prima stesura seminata e vanno ritoccati a mano: è esattamente
// per questo che sono dati e non codice.
//
// Di ogni terreno esistono più varianti, scelte per tassello di mondo con
// l'impronta delle coordinate. Serve a rompere la ripetizione: un solo
// disegno ripetuto su un prato si vede a colpo d'occhio come una stampa.
//
// I tasselli devono chiudere sui bordi, e lo fanno per costruzione: la figura
// è calcolata dentro i 16 pixel, quindi affiancandola a se stessa non ci sono
// cuciture.

// Da M7.18.47 i terreni di terra (erba, sterpaglia, sabbia, terra, roccia)
// sono a pixel pieni e non più a blocchi di due: fili d'erba con la punta al
// sole, steli secchi, increspature della sabbia, zolle, crepe nella roccia.
// Sei varianti per terreno e due toni in più per ciascuno (vedi
// tavolozza.js). Nascono da un generatore seminato — ogni figura sta dentro
// il tassello, a un pixel dal bordo, così affiancati non si cuciono male — e
// da qui in poi si ritoccano a mano come tutti gli altri disegni.

